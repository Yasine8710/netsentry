import { ArrowLeft } from 'lucide-react'
import { Link, useParams } from 'react-router-dom'
import { ProtocolChart, TrafficChart } from '../components/charts'
import { DemoBadge, ErrorState, Loading, Notice, Panel, StatCard, td, th } from '../components/ui'
import PacketTable from '../features/traffic/PacketTable'
import { useAsync } from '../hooks/useAsync'
import { api } from '../services/api'
import type { IpStat, PortStat, Severity } from '../types/api'
import { SEVERITIES } from '../types/api'
import { SeverityBadge } from '../components/ui'
import { formatBytes, formatDuration, formatIso, formatNumber, formatTs } from '../utils/format'

function IpTable({ title, rows }: { title: string; rows: IpStat[] }) {
  return (
    <Panel title={title}>
      <table className="w-full" aria-label={title}>
        <thead>
          <tr>
            <th scope="col" className={th}>
              IP
            </th>
            <th scope="col" className={`${th} text-right`}>
              Packets
            </th>
            <th scope="col" className={`${th} text-right`}>
              Bytes
            </th>
          </tr>
        </thead>
        <tbody className="divide-y divide-ink-600/40 font-mono">
          {rows.slice(0, 8).map((r) => (
            <tr key={r.ip}>
              <td className={td}>{r.ip}</td>
              <td className={`${td} text-right`}>{formatNumber(r.packets)}</td>
              <td className={`${td} text-right`}>{formatBytes(r.bytes)}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </Panel>
  )
}

function PortTable({ title, rows }: { title: string; rows: PortStat[] }) {
  return (
    <Panel title={title}>
      <table className="w-full" aria-label={title}>
        <thead>
          <tr>
            <th scope="col" className={th}>
              Port
            </th>
            <th scope="col" className={th}>
              Proto
            </th>
            <th scope="col" className={`${th} text-right`}>
              Packets
            </th>
          </tr>
        </thead>
        <tbody className="divide-y divide-ink-600/40 font-mono">
          {rows.slice(0, 8).map((r) => (
            <tr key={`${r.protocol}-${r.port}`}>
              <td className={td}>{r.port}</td>
              <td className={td}>{r.protocol}</td>
              <td className={`${td} text-right`}>{formatNumber(r.packets)}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </Panel>
  )
}

function KeyVals({
  title,
  data,
  empty,
}: {
  title: string
  data: Record<string, string | number>
  empty: string
}) {
  const entries = Object.entries(data)
  return (
    <Panel title={title}>
      {entries.length === 0 ? (
        <p className="text-sm text-slate-400">{empty}</p>
      ) : (
        <dl className="grid grid-cols-2 gap-x-4 gap-y-1 text-sm">
          {entries.map(([k, v]) => (
            <div key={k} className="contents">
              <dt className="text-slate-400">{k}</dt>
              <dd className="text-right font-mono text-slate-200">
                {typeof v === 'number' ? formatNumber(v) : v}
              </dd>
            </div>
          ))}
        </dl>
      )}
    </Panel>
  )
}

export default function TrafficDetail() {
  const { id = '' } = useParams()
  const { data: a, error, loading, reload } = useAsync(() => api.getAnalysis(id), [id])

  if (loading && !a) return <Loading label="Loading analysis" />
  if (error) {
    return (
      <div className="space-y-3">
        <Link to="/traffic" className="text-sm text-cyan-300 hover:underline">
          Back to analyses
        </Link>
        <ErrorState message={error} onRetry={reload} />
      </div>
    )
  }
  if (!a) return null
  const s = a.summary?.data
  const stats = a.parse_stats ?? {}

  return (
    <div className="space-y-6">
      <div>
        <Link
          to="/traffic"
          className="mb-2 inline-flex items-center gap-1 text-sm text-slate-400 hover:text-slate-200"
        >
          <ArrowLeft className="h-4 w-4" aria-hidden /> Analyses
        </Link>
        <h1 className="flex flex-wrap items-center gap-2 text-xl font-semibold text-slate-50">
          <span className="break-all">{a.filename}</span> {a.is_demo && <DemoBadge />}
        </h1>
        <p className="text-sm text-slate-400">
          {a.file_format?.toUpperCase()} · {formatBytes(a.file_size)} · analyzed {formatIso(a.created_at)}
        </p>
      </div>

      {a.is_demo && (
        <Notice tone="warn">
          This is synthetic demo data generated by NetSentry, not real network traffic.
        </Notice>
      )}
      {(a.notes ?? []).map((n) => (
        <Notice key={n} tone="warn">
          {n}
        </Notice>
      ))}
      {a.status !== 'completed' && <ErrorState message={a.error ?? `Analysis ${a.status}`} />}

      {s && (
        <>
          <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
            <StatCard
              label="Packets"
              value={formatNumber(s.packets)}
              hint={`${formatNumber(Number(stats.packets_read ?? 0))} read`}
            />
            <StatCard label="Bytes" value={formatBytes(s.bytes)} />
            <StatCard
              label="Duration"
              value={formatDuration(s.duration_s)}
              hint={s.first_ts ? formatTs(s.first_ts) : undefined}
            />
            <StatCard
              label="Unique IPs"
              value={`${formatNumber(s.unique_src_ips)} / ${formatNumber(s.unique_dst_ips)}`}
              hint="source / destination"
            />
          </div>

          <Panel
            title="Detections"
            action={
              <Link to={`/alerts?analysis_id=${a.id}`} className="text-xs text-cyan-400 hover:underline">
                Investigate
              </Link>
            }
          >
            <ul className="flex flex-wrap gap-3">
              {SEVERITIES.map((sev: Severity) => (
                <li key={sev} className="flex items-center gap-2">
                  <SeverityBadge severity={sev} />{' '}
                  <span className="font-mono text-sm">{a.alert_counts[sev] ?? 0}</span>
                </li>
              ))}
            </ul>
          </Panel>

          <Panel title="Traffic volume over time">
            <TrafficChart points={s.time_series.points} bucketS={s.time_series.bucket_s} />
          </Panel>

          <div className="grid gap-4 lg:grid-cols-2">
            <Panel title="Protocol breakdown">
              <ProtocolChart data={s.protocols} />
            </Panel>
            <div className="grid gap-4 sm:grid-cols-2">
              <KeyVals title="TCP flags" data={s.tcp} empty="No TCP flag data." />
              <KeyVals title="ICMP types" data={s.icmp} empty="No ICMP traffic." />
              <KeyVals title="UDP" data={{ packets: s.udp.packets }} empty="" />
              <KeyVals
                title="DNS"
                data={{ queries: s.dns.queries, responses: s.dns.responses, NXDOMAIN: s.dns.nxdomain }}
                empty="No DNS traffic."
              />
            </div>
          </div>

          <div className="grid gap-4 lg:grid-cols-2">
            <IpTable title="Top source IPs" rows={s.top_sources} />
            <IpTable title="Top destination IPs" rows={s.top_destinations} />
            <PortTable title="Top source ports" rows={s.top_src_ports} />
            <PortTable title="Top destination ports" rows={s.top_dst_ports} />
          </div>

          {s.dns.top_queried.length > 0 && (
            <Panel title="Most queried DNS names">
              <ul className="grid gap-1 font-mono text-sm sm:grid-cols-2">
                {s.dns.top_queried.map((d) => (
                  <li key={d.name} className="flex justify-between gap-3">
                    <span className="truncate">{d.name}</span>
                    <span className="text-slate-400">{d.count}</span>
                  </li>
                ))}
              </ul>
            </Panel>
          )}

          <PacketTable analysisId={a.id} />
        </>
      )}
    </div>
  )
}
